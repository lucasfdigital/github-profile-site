/** Largura do texto como o getbbox() do Pillow + 2px de margem, para as
 *  pílulas manterem o padding do BoardUI qualquer que seja o texto. */
export function medir(texto: string): number {
  if (!texto) return 2;
  let total = 0;
  for (const c of texto) total += (METRICAS[c] ?? [7.7, 0, 0])[0];
  const primeiro = METRICAS[texto[0]] ?? [0, 0, 0];
  const ultimo = METRICAS[texto[texto.length - 1]] ?? [0, 0, 0];
  return total - primeiro[1] - ultimo[2] + 2;
}
